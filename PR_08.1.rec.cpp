// Дано літерний рядок, який містить послідовність символів s[0], ..., s[n], ...
// 1. Вияснити, чи є в цій послідовності такі елементи s[i–1] , s[i+1]
// що s[i–1] – це кома (','), а s[i+1] – тире ('-'),
// та обчислити їх кількість.
// 2. Замінити кожну групу символів s[i–1] , s[i] , s[i+1] – таких, що
// s[i–1] – це кома (','), а s[i+1] – тире ('-')
// парою зірочок "**".
//
// Зауваження: тире у рядку задаємо ASCII-символом '-' (однобайтовий char);
// символ s[i] (середній) може бути будь-яким.

#define _CRT_SECURE_NO_WARNINGS
#include <iostream>
#include <cstring>

using namespace std;

// Рекурсивна функція обчислює кількість груп s[i-1], s[i], s[i+1],
// де s[i-1] == ',' та s[i+1] == '-'.
// Параметри: str - літерний рядок (не змінюється);
//            i   - позиція СЕРЕДНЬОГО символу поточної групи (при першому виклику i = 1).
// Результат: кількість знайдених груп, починаючи з позиції i і до кінця рядка.
int Count(char* str, int i)
{
	// у рядку з менш ніж трьох символів групи бути не може (захист від виходу за межі рядка)
	if (strlen(str) < 3)
		return 0;

	// умова ПРОДОВЖЕННЯ рекурсії: існує символ s[i+1], тобто він - не нуль-символ
	if (str[i + 1] != 0)
		if (str[i - 1] == ',' && str[i + 1] == '-')
			return 1 + Count(str, i + 1); // група знайдена: +1 і переходимо до наступної позиції
		else
			return Count(str, i + 1);     // групи немає: просто переходимо до наступної позиції
	else
		return 0; // умова ЗАВЕРШЕННЯ рекурсії: дійшли до кінця рядка - більше груп немає
}

// Рекурсивна функція будує у рядку dest копію рядка str,
// у якій кожну групу ',' <будь-який символ> '-' замінено парою зірочок "**".
// Параметри: dest - початок рядка-результату (під час рекурсії не змінюється);
//            str  - вхідний рядок (не змінюється);
//            t    - вказівник на поточну (кінцеву) позицію в рядку dest;
//            i    - позиція поточного символу у вхідному рядку str (початково 0).
// Результат: вказівник dest на сформований рядок.
char* Change(char* dest, const char* str, char* t, int i)
{
	// умова ЗАВЕРШЕННЯ рекурсії: вхідний рядок закінчився
	if (str[i] == '\0')
	{
		*t = '\0';    // завершуємо рядок-результат нуль-символом
		return dest;  // повертаємо початок сформованого рядка
	}

	// умова ПРОДОВЖЕННЯ рекурсії: перевіряємо групу з позиції i.
	// Порядок перевірок важливий: str[i+1] перевіряємо ДО читання str[i+2],
	// щоб не вийти за межі рядка (&& обчислюється зліва направо).
	if (str[i] == ',' && str[i + 1] != '\0' && str[i + 2] == '-')
	{
		strcat_s(t, 101, "**");                      // дописуємо дві зірочки
		return Change(dest, str, t + 2, i + 3); // t - за зірочки, i - за групу з трьох символів
	}
	else
	{
		*t++ = str[i++];  // групи немає - копіюємо поточний символ як є
		*t = '\0';        // підтримуємо завершальний нуль-символ рядка-результату
		return Change(dest, str, t, i); // продовжуємо з наступного символу
	}
}

int main()
{
	char str[101];
	cout << "Enter string:" << endl;
	cin.getline(str, 100); // getline, щоб можна було вводити пробіли

	// 1) кількість груп "кома - символ - тире"; починаємо з i = 1 (потрібен s[i-1])
	cout << "String contained " << Count(str, 1) << " groups of ', -'" << endl;

	// 2) заміна груп на "**"; результат записується у новий рядок dest1
	char* dest1 = new char[151];
	dest1[0] = '\0'; // dest1 спочатку порожній рядок
	char* dest2;
	dest2 = Change(dest1, str, dest1, 0);
	cout << "Modified string (param) : " << dest1 << endl;  // результат через параметр
	cout << "Modified string (result): " << dest2 << endl;  // результат через значення функції

	delete[] dest1; // звільняємо пам'ять (dest2 вказує на ту саму область)
	return 0;
}